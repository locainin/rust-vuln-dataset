import itertools
import os
import sys

from compare.core import ADVISORY_FIELDS, DATASET_ORDER
from compare.repository import HALURUST_REPOSITORY, HALURUST_REVISION


def markdown_table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("| " + " | ".join("---" for _ in headers) + " |")
    for row in rows:
        cells = []
        for value in row:
            cells.append(str(value).replace("|", "\\|").replace("\n", " "))
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def build_report(result):
    matches, counts, differences, retained, lock = result
    pairs = {row[:4] for row in matches if row[4] in ADVISORY_FIELDS}
    unresolved = {row[:4] for row in matches} - pairs
    lines = []
    lines.append("# Exact source-field comparison")
    lines.append("")
    lines.append(
        "Generated by compare.py directly from existing inputs; "
        "no inferred defect or lineage classifications."
    )
    lines.append("")

    lines.append("## Inputs")
    lines.append("")
    lines.append(
        "- RustXec (tracked local files): Verification/source/metadata.csv; "
        "manual/RUSTSEC-*/metadata.yaml; "
        "manual/RUSTSEC-*/pairs/*/{vulnerable,fixed}.rs"
    )
    lines.append(
        "- HaluRust retention: tracked local halurust/cases/; "
        "halurust/cases/CVE-*/metadata.yaml where present"
    )
    lines.append(
        f"- HaluRust inventory: {HALURUST_REPOSITORY} "
        f"at `{HALURUST_REVISION}`; Git-tracked "
        "Data/Positive/*.rs and Data/Negative/*.rs with identical filename sets"
    )
    lines.append("- RustMizan (tracked local files): rustmizan/source-lock.yaml and rustmizan/mizan.json")
    lines.append(
        f"- RustMizan upstream: {lock['upstream']['repository']} "
        f"at `{lock['upstream']['revision']}`; tracked mizan.json, "
        "samples/vuln-*/README.md table fields, "
        "and tracked *.rs files under every declared sample project"
    )
    lines.append("")
    lines.append(
        "HaluRust records use literal upstream filename stems; CVE identifiers "
        "come from the filename portion before the CWE suffix. No HaluRust "
        "import manifest is used. Local retention comes only from tracked cases."
    )
    lines.append("")

    lines.append("## Counts")
    lines.append("")
    count_rows = []
    for family in DATASET_ORDER:
        total = 0
        other_dispositions = []
        for (source_family, status), count in sorted(counts.items()):
            if source_family != family:
                continue
            total += count
            if status != "retained":
                other_dispositions.append(f"{status}: {count}")
        count_rows.append(
            (family, total, counts[family, "retained"], "; ".join(other_dispositions))
        )
    lines.extend(markdown_table(
        ["Dataset", "Source records", "Retained", "Other dispositions"],
        count_rows,
    ))
    lines.append("")
    lines.append(
        "Distinct cross-family pairs with an exact advisory-ID intersection: "
        f"**{len(pairs)}**. These are literal field matches, "
        "not proof that samples represent identical defects."
    )
    lines.append("")
    pair_count_rows = []
    for family_a, family_b in itertools.combinations(DATASET_ORDER, 2):
        count = 0
        for pair in pairs:
            if pair[0] == family_a and pair[2] == family_b:
                count += 1
        pair_count_rows.append((family_a, family_b, count))
    lines.extend(markdown_table(
        ["Dataset A", "Dataset B", "Pairs with identifier matches"],
        pair_count_rows,
    ))
    lines.append("")

    lines.append("## Intersections")
    lines.append("")
    lines.append(
        "Each matching field/value is reported once per pair, with its source "
        "locations. Commit roles are not conflated; source hashes compare "
        "complete nonempty files byte-for-byte, without whitespace "
        "normalization or extraction."
    )
    lines.append("")
    lines.extend(markdown_table(
        [
            "Dataset A", "Record A", "Dataset B", "Record B",
            "Matching field", "Matching value", "Source A", "Source B",
        ],
        matches,
    ))
    hash_rows = sum(row[4] == "Source SHA-256" for row in matches)
    lines.append("")
    lines.append(
        f"Exact source-hash intersection rows: {hash_rows}. Different file "
        "boundaries or formatting can prevent a match; absence is not "
        "evidence of unrelated defects."
    )
    lines.append("")

    lines.append("## Source-field differences")
    lines.append("")
    lines.extend(markdown_table(
        ["Dataset", "Record", "Source A", "Value A", "Source B", "Value B"],
        differences,
    ))
    lines.append("")
    lines.append(
        "RustXec comparisons use current curated metadata where present, "
        "while the table above preserves differing historical CSV identifiers. "
        "No CSV values are rewritten."
    )
    lines.append("")
    for native_id, entry in lock["cases"].items():
        provenance = entry.get("provenance", {})
        if provenance.get("relationship"):
            lines.append(
                f"Existing source-lock statement for {native_id}: "
                f"{provenance['relationship']}. "
                + " ".join(entry.get("evidence", [])[:2])
            )
            lines.append("")

    lines.append("## Unresolved")
    lines.append("")
    if unresolved:
        lines.append(
            "These pairs share a commit value or source hash but no exact "
            "advisory identifier in the fields read. The intersection alone "
            "does not establish vulnerability identity."
        )
        lines.append("")
        lines.extend(markdown_table(
            ["Dataset A", "Record A", "Dataset B", "Record B"], sorted(unresolved),
        ))
    else:
        lines.append(
            "No commit/hash-only pair lacks an exact identifier intersection "
            "in this run. This does not establish that all possible defect "
            "lineages have been resolved; absent identifiers and differently "
            "scoped source files remain unassessed."
        )
    both_retained = []
    for pair in pairs:
        if (pair[0], pair[1]) in retained and (pair[2], pair[3]) in retained:
            both_retained.append(pair)
    both_retained.sort()
    lines.append("")
    lines.append(
        "Identifier-matching pairs with both records retained: "
        + (str(both_retained) if both_retained else "none")
    )
    lines.append("")
    lines.append(
        "No CWE, package-name, function-name, fuzzy-source, or prose-mechanism "
        "comparison is performed. Broad advisory IDs may cover several issues; "
        "a matching field is not an inferred same-defect classification."
    )
    lines.append("")
    return "\n".join(lines)


def color_text(text, color):
    if sys.stdout.isatty() and "NO_COLOR" not in os.environ:
        return f"\033[{color}m{text}\033[0m"
    return text


def print_status(message):
    print(color_text("  • ", "36") + message, flush=True)


def print_summary(result, output):
    matches, counts, _, retained, _ = result
    pairs = {row[:4] for row in matches if row[4] in ADVISORY_FIELDS}
    unresolved = {row[:4] for row in matches} - pairs
    both_retained = []
    for pair in pairs:
        if (pair[0], pair[1]) in retained and (pair[2], pair[3]) in retained:
            both_retained.append(pair)

    print()
    print(color_text("  ✓ Comparison complete", "1;32"))
    print()
    print(f"  {'Dataset':<14} {'Original':>8} {'Retained':>10} {'Not retained':>12}")
    for family in DATASET_ORDER:
        total = sum(count for (name, _), count in counts.items() if name == family)
        kept = counts[family, "retained"]
        print(f"  {family:<14} {total:>8} {kept:>10} {total - kept:>12}")
    print()
    print(color_text(
        f"  {sum(counts.values())} records · {len(pairs)} advisory-ID pairs"
        f" · {len(matches)} matching-field rows", "1;36",
    ))
    for family_a, family_b in itertools.combinations(DATASET_ORDER, 2):
        total = sum(pair[0] == family_a and pair[2] == family_b for pair in pairs)
        print(f"    {family_a} ↔ {family_b}: {total}")
    print()
    print(f"  Commit/hash-only unresolved pairs: {len(unresolved)}")
    print(f"  Matches with both records retained: {len(both_retained)}")
    print(color_text("  ✓ Pinned revisions and tracked inputs verified", "32"))
    print(color_text("  ✓ Local inputs match committed repository state", "32"))
    print(f"  Report: {output}")
    print(color_text("  Exact intersections only; hidden defect lineages are not ruled out.", "2"))
    print()
